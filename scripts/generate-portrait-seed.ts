/**
 * Turn `legacy-import/portraits.json` into a seed migration.
 *
 *   npx tsx --tsconfig tsconfig.scripts.json scripts/generate-portrait-seed.ts \
 *     legacy-import/portraits.json migrations/0040_seed_portraits.sql
 *
 * Same contract as `generate-page-seed.ts` and `generate-press-seed.ts`: the
 * output is reproducible, so re-running it must produce a byte-identical file
 * or somebody has edited a migration by hand. Nothing here reads a database.
 *
 * Two tables per portrait. `media_assets` first, because the photograph is
 * what makes the row worth having and `content_portraits.photo_id` is NOT
 * NULL; then `content_items` and `content_portraits`, joined back to the asset
 * by its `src`, which carries a UNIQUE key. That join is what keeps this
 * re-runnable: every statement is `INSERT IGNORE` or keyed on a unique column,
 * so applying it twice changes nothing.
 *
 * The portraits are seeded **published**. Unlike the press archive — 686 rows
 * left as drafts because no date could be established and a press release
 * without one is undatable — a photograph of a named office-bearer needs
 * nothing established. It is published on lcci.com.pk today, beside that name.
 */

import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { slugify } from "@/content/fields";

interface Portrait {
  name: string;
  term: string | null;
  role: string | null;
  source: string;
  sourceImage: string;
  src: string;
  width: number;
  height: number;
}

interface Manifest {
  sources: string[];
  portraits: Portrait[];
  skipped: string[];
}

/** A MySQL string literal. */
function q(value: string | null): string {
  if (value === null) return "NULL";
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}

/**
 * What a screen reader is told about the picture.
 *
 * It names the person, which is a departure from the rule in
 * `scripts/prepare-photos.mjs` and a considered one — see the note at the top
 * of `scripts/import-portraits.ts`. The short version: on the hero collage
 * nobody had said who was in the frame, and here the chamber prints the name
 * beside the face on its own page.
 *
 * "Portrait of" rather than "Photograph of": every one of these is a posed
 * head-and-shoulders studio shot, which is what a reader who cannot see it
 * most wants to know, and it distinguishes them from the event photography in
 * `public/photos`.
 */
function altFor(portrait: Portrait): string {
  const who = portrait.role ? `${portrait.name}, ${portrait.role}` : portrait.name;
  return `Portrait of ${who}.`;
}

function main(): number {
  const [input = "legacy-import/portraits.json", output = "migrations/0040_seed_portraits.sql"] =
    process.argv.slice(2);

  const manifest = JSON.parse(readFileSync(input, "utf8")) as Manifest;

  // Sorted by name so the output order never depends on the order the
  // importer happened to walk the pages in.
  const portraits = [...manifest.portraits].sort((a, b) => a.name.localeCompare(b.name));

  const slugs = new Set<string>();
  const lines: string[] = [];

  lines.push(
    "-- The chamber's people, with their photographs.",
    "--",
    `-- Generated by scripts/generate-portrait-seed.ts from ${input}.`,
    "-- Do not edit. Re-run the generator; the output is byte-for-byte",
    "-- reproducible, so a diff here means somebody edited a migration by hand.",
    "--",
    `-- ${portraits.length} portraits, lifted from:`,
    ...manifest.sources.map((s) => `--   ${s}`),
    "--",
    "-- The pairing of face to name is the old site's own, read out of the raw",
    "-- HTML because the imported page bodies have no images in them — see",
    "-- scripts/import-portraits.ts for why.",
    "--",
    "-- These are PUBLISHED, not drafts. A photograph of a named office-bearer",
    "-- needs no date established before it can be shown; it is on lcci.com.pk",
    "-- today, beside that name.",
    "--",
    "-- What is deliberately NOT here: the personal mobile numbers and personal",
    "-- email addresses that presidents.php and excomm.php print beside these",
    "-- faces. Those are already on /about/past-leadership as part of the page",
    "-- body lifted from the old site and cannot be removed from it without",
    "-- changing the chamber's words — but nothing requires this repository to",
    "-- copy them a second time into a new, queryable table, so it does not.",
    "",
  );

  if (manifest.skipped.length > 0) {
    lines.push("-- Not imported:");
    for (const note of manifest.skipped) lines.push(`--   ${note}`);
    lines.push("");
  }

  for (const portrait of portraits) {
    const slug = slugify(portrait.name);
    if (slug === "") throw new Error(`no slug for ${portrait.name}`);
    if (slugs.has(slug)) throw new Error(`two portraits share the slug ${slug}`);
    slugs.add(slug);

    lines.push(
      `-- ${portrait.name}${portrait.role ? ` (${portrait.role})` : ""}`,
      `--   ${portrait.sourceImage}`,
      "INSERT IGNORE INTO media_assets (src, alt_en, width, height, department_code)",
      `VALUES (${q(portrait.src)}, ${q(altFor(portrait))}, ${portrait.width}, ${portrait.height}, 'info');`,
      "",
      "INSERT IGNORE INTO content_items",
      "  (content_type, slug, title_en, status, published_at, department_code, sort_order, updated_at)",
      `VALUES ('portrait', ${q(slug)}, ${q(portrait.name)}, 'published', NOW(3), 'info', 0, NOW(3));`,
      "",
      "INSERT IGNORE INTO content_portraits (content_item_id, role, term, photo_id)",
      `SELECT ci.id, ${q(portrait.role)}, ${q(portrait.term)}, ma.id`,
      "  FROM content_items ci",
      `  JOIN media_assets ma ON ma.src = ${q(portrait.src)}`,
      ` WHERE ci.content_type = 'portrait' AND ci.slug = ${q(slug)};`,
      "",
    );
  }

  writeFileSync(output, `${lines.join("\n")}`, "utf8");
  process.stdout.write(`${output}: ${portraits.length} portraits\n`);
  return 0;
}

process.exit(main());
