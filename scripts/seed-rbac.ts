/**
 * Generate the RBAC seed migration from the TypeScript vocabulary.
 *
 *   npm run seed:rbac > migrations/0005_seed_rbac.sql
 *
 * Generated rather than hand-written because the permission codes are a closed
 * union in `src/server/permissions.ts` and the grants are rows in the database,
 * so the one thing that must not happen is the two disagreeing — a permission
 * that exists in TypeScript and not in `permissions` makes every check against
 * it fail silently, which is a role that quietly cannot do its job.
 *
 * `tests/rbac-seed.test.ts` asserts the committed file still matches, so
 * changing a role's grants without regenerating fails the suite.
 */

import { PERMISSIONS, PERMISSION_CODES, ROLE_SEED, ROLE_CODES } from "../src/server/permissions";

function quote(value: string): string {
  // Single quotes doubled, which is the SQL standard escape and is what MySQL
  // accepts regardless of NO_BACKSLASH_ESCAPES. Nothing here is user input —
  // these are literals from a TypeScript constant — but a label containing an
  // apostrophe is entirely plausible and would otherwise produce broken SQL.
  return `'${value.replace(/'/g, "''")}'`;
}

const lines: string[] = [];

lines.push("-- 0005 — seed the RBAC vocabulary and the default grants.");
lines.push("--");
lines.push("-- GENERATED by `npm run seed:rbac` from src/server/permissions.ts.");
lines.push("-- Do not edit by hand; regenerate. tests/rbac-seed.test.ts checks that");
lines.push("-- this file still matches the TypeScript, so an edit to one without the");
lines.push("-- other fails the suite.");
lines.push("--");
lines.push("-- Idempotent, so it can be pasted into phpMyAdmin when SSH is unavailable");
lines.push("-- — which it will be. Note what that means, though: this is a *seed*. Once");
lines.push("-- it has run the database is authoritative, because an administrator may");
lines.push("-- adjust grants without a deploy. Re-running it restores the defaults for");
lines.push("-- anything that has been removed.");
lines.push("");

lines.push("-- The permission vocabulary. Also a closed union in TypeScript, so a");
lines.push("-- misspelled code is a compile error rather than a check that never matches.");
lines.push("INSERT INTO permissions (code, label_en, domain) VALUES");
lines.push(
  PERMISSION_CODES.map((code) => {
    const permission = PERMISSIONS[code];
    return `  (${quote(code)}, ${quote(permission.label)}, ${quote(permission.domain)})`;
  }).join(",\n") + "",
);
// `VALUES()` rather than MySQL 8.0.20's row-alias form, deliberately: the
// alias syntax is a parse error on MariaDB, and cPanel ships MariaDB far more
// often than MySQL. `VALUES()` is deprecated on MySQL 8 and works on both,
// which is the right trade for a file that may be pasted into phpMyAdmin.
lines.push("ON DUPLICATE KEY UPDATE label_en = VALUES(label_en), domain = VALUES(domain);");
lines.push("");

lines.push("-- The roles. Five from spec section 8.3, plus `cashier` and");
lines.push("-- `membership_approver`: the printed form carries a cashier block with its");
lines.push("-- own signature, and somebody must *grant* membership. One officer doing");
lines.push("-- both verification and approval collapses the separation of duties that");
lines.push("-- the checklist, the staff signature, the cashier signature and the");
lines.push("-- approval block exist to create.");
lines.push("INSERT INTO roles (code, label_en, is_system) VALUES");
lines.push(
  ROLE_CODES.map((code) => {
    const role = ROLE_SEED[code];
    return `  (${quote(code)}, ${quote(role.label)}, ${role.isSystem ? 1 : 0})`;
  }).join(",\n"),
);
lines.push("ON DUPLICATE KEY UPDATE label_en = VALUES(label_en), is_system = VALUES(is_system);");
lines.push("");

for (const roleCode of ROLE_CODES) {
  const role = ROLE_SEED[roleCode];

  if (role.permissions === "all") {
    lines.push(`-- ${role.label}: every permission, selected from the table rather than`);
    lines.push("-- enumerated, so this statement stays correct as permissions are added.");
    lines.push("-- A later migration that adds one should repeat it.");
    lines.push("INSERT IGNORE INTO role_permissions (role_code, permission_code)");
    lines.push(`SELECT ${quote(roleCode)}, code FROM permissions;`);
    lines.push("");
    continue;
  }

  lines.push(`-- ${role.label}`);
  lines.push("INSERT IGNORE INTO role_permissions (role_code, permission_code) VALUES");
  lines.push(
    role.permissions
      .map((permission) => `  (${quote(roleCode)}, ${quote(permission)})`)
      .join(",\n") + ";",
  );
  lines.push("");
}

lines.push("-- No user is seeded. The first super-admin account is created by an");
lines.push("-- explicit, audited command rather than by a migration, because a");
lines.push("-- migration that creates an administrator creates one with a password");
lines.push("-- that is in the repository.");

process.stdout.write(lines.join("\n") + "\n");
