/**
 * Generate the working-day calendar seed.
 *
 *   npm run seed:calendar        writes migrations/0010_seed_calendar.sql
 *
 * Same pattern as `seed-rbac.ts`: a generator that emits plain SQL, so the
 * result can be pasted into phpMyAdmin when SSH to the shared host is not
 * cooperating, and so the seed is reviewable as a diff rather than hidden
 * inside a TypeScript loop that ran once.
 *
 * What this seeds and what it deliberately does not:
 *
 * It marks Saturdays and Sundays as non-working and every other day as
 * working. That is an *assumption* — many Pakistani chambers work a six-day
 * week, and whether the LCCI secretariat does is an open question for the
 * chamber. Every row is written with `confidence = 'provisional'` and a
 * `source` that says so, precisely so the assumption is visible in the data
 * rather than buried here.
 *
 * It seeds **no public holidays at all**, and that is not an omission.
 * Pakistani public holidays cannot be computed: Eid, Ashura and Eid
 * Milad-un-Nabi are lunar and officially notified only days in advance, Eid
 * routinely shifts on moon sighting, bank holidays matter because a pay order
 * cannot be issued or realised on one, and Lahore adds ad-hoc closures for
 * security and smog. A generator that invented them would produce a calendar
 * that looks authoritative and quietly misses paid deadlines. They are entered
 * through the admin screen as they are notified, which is also when
 * `needs_recompute` goes up on the clocks that span them.
 */

import { writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

/**
 * Four years.
 *
 * Long enough that a 40-working-day clock started at any point inside the
 * first three lands on a date the table knows about — a clock whose due date
 * falls off the end of the calendar would be an SLA that silently cannot be
 * calculated. The admin screen extends it; this is the runway.
 */
const FIRST_YEAR = 2026;
const LAST_YEAR = 2029;

const SOURCE =
  "Generated seed: Monday-Friday assumed, no public holidays. Confirm the secretariat working week.";

/** Rows per INSERT. Keeps the file readable and the statements a sane size. */
const BATCH = 40;

function* eachDate(from: Date, to: Date): Generator<Date> {
  // UTC throughout. A local-time loop across a DST boundary either repeats or
  // skips a day, and although Pakistan has no DST today the bug would be
  // silent if that ever changed.
  for (let d = new Date(from); d <= to; d.setUTCDate(d.getUTCDate() + 1)) {
    yield new Date(d);
  }
}

function iso(date: Date): string {
  return date.toISOString().slice(0, 10);
}

function main(): number {
  const from = new Date(Date.UTC(FIRST_YEAR, 0, 1));
  const to = new Date(Date.UTC(LAST_YEAR, 11, 31));

  const rows: string[] = [];
  let working = 0;

  for (const date of eachDate(from, to)) {
    const day = date.getUTCDay();
    const isWeekend = day === 0 || day === 6;
    const label = day === 0 ? "Sunday" : day === 6 ? "Saturday" : null;

    if (!isWeekend) working += 1;

    rows.push(
      `  ('${iso(date)}', ${isWeekend ? 0 : 1}, ` +
        `${label === null ? "NULL" : `'${label}'`}, 'provisional', ` +
        `'${SOURCE.replace(/'/g, "''")}', UTC_TIMESTAMP(3))`,
    );
  }

  const statements: string[] = [];
  for (let i = 0; i < rows.length; i += BATCH) {
    statements.push(
      "INSERT INTO working_day_calendar\n" +
        "  (cal_date, is_working_day, label_en, confidence, source, updated_at)\n" +
        "VALUES\n" +
        rows.slice(i, i + BATCH).join(",\n") +
        ";",
    );
  }

  const header = [
    `-- 0010 — working-day calendar, ${FIRST_YEAR} to ${LAST_YEAR}.`,
    "--",
    "-- GENERATED by scripts/seed-calendar.ts. Do not edit by hand: regenerate.",
    "--",
    `-- ${rows.length} days, of which ${working} are marked working.`,
    "--",
    "-- Monday to Friday is an ASSUMPTION and every row says so: `confidence` is",
    "-- 'provisional' and `source` records that the secretariat working week is",
    "-- unconfirmed. Many Pakistani chambers work a six-day week.",
    "--",
    "-- No public holidays are seeded. Eid, Ashura and Eid Milad-un-Nabi are",
    "-- lunar and notified days in advance, Eid shifts on moon sighting, bank",
    "-- holidays stop a pay order being issued or realised, and Lahore adds",
    "-- closures for security and smog. Computing them would produce a calendar",
    "-- that looks authoritative and misses paid deadlines; they are entered",
    "-- through the admin screen as they are notified.",
    "",
  ].join("\n");

  const file = path.join(process.cwd(), "migrations", "0010_seed_calendar.sql");
  writeFileSync(file, `${header}\n${statements.join("\n\n")}\n`, "utf8");

  console.log(
    `Wrote ${path.relative(process.cwd(), file)}: ` +
      `${rows.length} days (${working} working), ${statements.length} statements.`,
  );
  return 0;
}

process.exit(main());
